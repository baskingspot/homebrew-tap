#!/usr/bin/env python3
"""Write a Homebrew cask for every baskingspot program that has a release.

A program opts in by having `.github/release.yaml`, the file its release
workflow reads. For each such public repo this finds the latest release, reads
the SHA256SUMS asset, and writes `Casks/<repo>.rb`. A cask whose repo no longer
qualifies is removed. Run by `.github/workflows/update.yml` every hour and by
hand with `just update`. It needs `gh` and `yq`, and it changes only `Casks/`.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

ORG = "baskingspot"
MARKER = "# Generated by tools/update.py"

# A Zig target triple names the OS and the CPU. Anything else is an error, so
# a new target is a decision and not a silent skip.
PLATFORMS = {
    "x86_64-linux": ("linux", "intel"),
    "aarch64-linux": ("linux", "arm"),
    "x86_64-macos": ("macos", "intel"),
    "aarch64-macos": ("macos", "arm"),
}


@dataclass
class Target:
    os: str
    cpu: str
    asset: str


@dataclass
class Program:
    repo: str
    binary: str
    description: str
    homepage: str
    targets: list[Target]


class NotFoundError(RuntimeError):
    """GitHub answered 404. Any other failure is a real error and stops the run."""


def run(*args: str, stdin: str | None = None) -> str:
    result = subprocess.run(
        args, input=stdin, capture_output=True, text=True, check=False
    )
    if result.returncode != 0:
        message = f"{' '.join(args)}: {result.stderr.strip()}"
        if "HTTP 404" in result.stderr:
            raise NotFoundError(message)
        raise RuntimeError(message)
    return result.stdout


def gh_json(path: str) -> Any:
    return json.loads(run("gh", "api", "--paginate", path) or "null")


def platform_of(target: str) -> tuple[str, str]:
    """The (os, cpu) of a Zig target such as `x86_64-linux-musl`."""
    parts = target.split("-")
    key = "-".join(parts[:2])
    if key not in PLATFORMS:
        raise ValueError(f"no Homebrew platform for the target {target!r}")
    return PLATFORMS[key]


def parse_release_yaml(text: str) -> dict[str, Any]:
    return json.loads(run("yq", "-o=json", ".", stdin=text))


def program_from(repo: dict[str, Any], config: dict[str, Any]) -> Program:
    targets = []
    for entry in config["targets"]:
        os_name, cpu = platform_of(entry["target"])
        targets.append(Target(os_name, cpu, entry["asset"]))
    return Program(
        repo=repo["name"],
        binary=config["binary"],
        description=str(repo.get("description") or "").rstrip("."),
        homepage=str(repo.get("homepage") or repo["html_url"]),
        targets=targets,
    )


def parse_sums(text: str) -> dict[str, str]:
    """`sha256sum` output as {file name: hash}."""
    sums = {}
    for line in text.splitlines():
        match = re.fullmatch(r"([0-9a-f]{64})\s+\*?(\S+)", line.strip())
        if match:
            sums[match.group(2)] = match.group(1)
    return sums


def render(program: Program, tag: str, sums: dict[str, str]) -> str:
    """The cask for one program at one release. Pure, so it is tested."""
    version = tag.removeprefix("v")
    token, binary = program.repo, program.binary

    def block(os_name: str) -> list[str]:
        lines: list[str] = []
        for target in (t for t in program.targets if t.os == os_name):
            file = f"{binary}-{tag}-{target.asset}.tar.gz"
            if file not in sums:
                raise ValueError(f"{program.repo} {tag} has no checksum for {file}")
            folder = f"{binary}-v#{{version}}-{target.asset}"
            lines += [
                f"    on_{target.cpu} do",
                f'      url "https://github.com/{ORG}/{program.repo}/releases/download/v#{{version}}/{folder}.tar.gz"',
                f'      sha256 "{sums[file]}"',
                f'      binary "{folder}/{binary}"',
                "    end",
            ]
        return [f"  on_{os_name} do", *lines, "  end", ""] if lines else []

    body = [
        f"{MARKER} from {ORG}/{program.repo}'s latest release. Do not edit.",
        f'cask "{token}" do',
        f'  name "{token}"',
        f'  desc "{program.description}"',
        f'  homepage "{program.homepage}"',
        f'  version "{version}"',
        "",
        "  livecheck do",
        "    url :url",
        "    strategy :github_latest",
        "  end",
        "",
        *block("macos"),
        *block("linux"),
        "  # The release binaries are not signed or notarized, so macOS would quarantine them.",
        "  postflight do",
        "    if OS.mac?",
        '      system_command "/usr/bin/xattr",',
        '                     args: ["-dr", "com.apple.quarantine", staged_path.to_s]',
        "    end",
        "  end",
        "end",
        "",
    ]
    return "\n".join(body)


def discover() -> list[Program]:
    programs = []
    for repo in gh_json(f"orgs/{ORG}/repos?type=public&per_page=100"):
        if repo["archived"] or repo["fork"] or repo["private"]:
            continue
        try:
            raw = run(
                "gh",
                "api",
                f"repos/{ORG}/{repo['name']}/contents/.github/release.yaml",
                "--jq",
                ".content",
            )
        except NotFoundError:
            continue
        text = run("base64", "-d", stdin=raw)
        programs.append(program_from(repo, parse_release_yaml(text)))
    return programs


def latest(program: Program) -> tuple[str, dict[str, str]] | None:
    try:
        release = json.loads(
            run("gh", "api", f"repos/{ORG}/{program.repo}/releases/latest")
        )
    except NotFoundError:
        return None
    asset = next((a for a in release["assets"] if a["name"] == "SHA256SUMS"), None)
    if asset is None:
        return None
    text = run(
        "gh",
        "api",
        "-H",
        "Accept: application/octet-stream",
        f"repos/{ORG}/{program.repo}/releases/assets/{asset['id']}",
    )
    return release["tag_name"], parse_sums(text)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--casks", default="Casks", help="the directory to write")
    args = parser.parse_args()
    out = Path(args.casks)
    out.mkdir(exist_ok=True)
    opted_in: set[str] = set()
    for program in discover():
        opted_in.add(f"{program.repo}.rb")
        found = latest(program)
        if found is None:
            print(f"{program.repo}: no release with SHA256SUMS yet, skipped")
            continue
        tag, sums = found
        (out / f"{program.repo}.rb").write_text(
            render(program, tag, sums), encoding="utf-8"
        )
        print(f"{program.repo}: {tag}")
    for stale in out.glob("*.rb"):
        if stale.name not in opted_in and stale.read_text(encoding="utf-8").startswith(
            MARKER
        ):
            stale.unlink()
            print(f"{stale.stem}: removed, it no longer has a release.yaml")
    return 0


if __name__ == "__main__":
    sys.exit(main())
